    /// <summary>Returns today's date in BS, using Nepal Standard Time (UTC+5:45).</summary>
    public static (int Year, int Month, int Day) GetTodayBs()
    {
        var nstNow = DateTimeOffset.UtcNow.ToOffset(NstOffset).Date;
        return AdToBs(nstNow);
    }

    /// <summary>Converts a Gregorian date to Bikram Sambat.</summary>
    public static (int Year, int Month, int Day) AdToBs(DateTime ad)
    {
        if (ad.Date < StartAdDate)
            throw new ArgumentOutOfRangeException(nameof(ad), "Date is before supported range.");

        int totalDays = (int)(ad.Date - StartAdDate).TotalDays;

        int bsYear  = StartBsYear;
        int bsMonth = StartBsMonth;
        int bsDay   = StartBsDay;

        // Walk through years
        int idx = 0;
        while (idx < YearData.Length)
        {
            int daysInYear = YearData[idx].Sum();
            if (totalDays < daysInYear) break;
            totalDays -= daysInYear;
            bsYear++;
            idx++;
        }

        if (idx >= YearData.Length)
            throw new ArgumentOutOfRangeException(nameof(ad), "Date exceeds supported BS range.");

        // Walk through months of the current year
        for (int m = 0; m < 12; m++)
        {
            int dim = YearData[idx][m];
            if (totalDays < dim)
            {
                bsMonth = m + 1;
                bsDay   = totalDays + 1;
                break;
            }
            totalDays -= dim;
        }

        return (bsYear, bsMonth, bsDay);
    }

    /// <summary>Returns days in a given BS month (1-based month).</summary>
    public static int DaysInBsMonth(int bsYear, int bsMonth)
    {
        int idx = bsYear - StartBsYear;
        if (idx < 0 || idx >= YearData.Length || bsMonth < 1 || bsMonth > 12)
            return 32; // safe fallback
        return YearData[idx][bsMonth - 1];
    }

    /// <summary>
    /// Calculates age in full BS years given a DOB string "YYYY-MM-DD" in BS.
    /// Returns null if dobBs is null/empty or cannot be parsed.
    /// </summary>
    public static int? CalculateAgeBs(string? dobBs)
    {
        if (string.IsNullOrWhiteSpace(dobBs)) return null;

        var parts = dobBs.Split('-');
        if (parts.Length < 3) return null;
        if (!int.TryParse(parts[0], out int dobYear)) return null;
        if (!int.TryParse(parts[1], out int dobMonth)) return null;
        if (!int.TryParse(parts[2], out int dobDay)) return null;

        var (todayYear, todayMonth, todayDay) = GetTodayBs();

        int age = todayYear - dobYear;
        // If birthday hasn't occurred yet this year, subtract 1
        if (todayMonth < dobMonth || (todayMonth == dobMonth && todayDay < dobDay))
            age--;

        return age < 0 ? 0 : age;
    }

    /// <summary>
    /// Returns an approximate BS DOB string "YYYY-MM-DD" given an age in years.
    /// Places the birthday on Baisakh 1 (month 1, day 1) of the birth year,
    /// which gives an age that is correct for most of the BS year.
    /// </summary>
    public static string ApproxDobBsFromAge(int age)
    {
        var (todayYear, todayMonth, todayDay) = GetTodayBs();
        int birthYear = todayYear - age;

        // Clamp day to valid range for the birth month
        int day = todayDay;
        int maxDay = DaysInBsMonth(birthYear, todayMonth);
        if (day > maxDay) day = maxDay;

        return $"{birthYear:D4}-{todayMonth:D2}-{day:D2}";
    }

    /// <summary>Formats a BS date tuple as "YYYY-MM-DD".</summary>
    public static string FormatBs(int year, int month, int day) =>
        $"{year:D4}-{month:D2}-{day:D2}";

